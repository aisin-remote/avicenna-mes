SELECT TABLE_NAME,COLUMN_NAME,DATA_TYPE,CHARACTER_MAXIMUM_LENGTH
FROM [aisinbisa_sap_stagging].INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA='dbo' AND TABLE_NAME IN
('TT_DELIVERY','TT_DELIVERY_ITEM','TT_GOODS_MOVEMENT_H','TT_GOODS_MOVEMENT_L','TT_PURCHASE_RECEIPT_H','TT_PURCHASE_RECEIPT_L','TM_MATDOC_IP_H','TM_MATDOC_IP_L')
ORDER BY TABLE_NAME,ORDINAL_POSITION;

SELECT TOP (20) H.CHR_PLANT,H.CHR_PLANT_TO,H.CHR_TYPE_TRANS,H.CHR_MVMT_TYPE,
L.CHR_DEL_NO,L.CHR_DEL_ITEM,L.CHR_PDS_NO,L.CHR_STATUS,L.CHR_MATDOC,
L.CHR_PGI_DOC,L.CHR_PGI_YEAR,L.CHR_PGI_STATUS,L.CHR_GR_DOC,L.CHR_GR_YEAR,L.CHR_GR_STATUS,
L.CHR_MVMT_TYPE_L,L.CHR_TYPE_TRANS_L,L.CHR_PICK_STATUS,L.CHR_COMPLETE_STATUS,L.CHR_MESSAGE_DO
FROM [aisinbisa_sap_stagging].dbo.TT_GOODS_MOVEMENT_H H
JOIN [aisinbisa_sap_stagging].dbo.TT_GOODS_MOVEMENT_L L ON L.INT_NUMBER=H.INT_NUMBER
ORDER BY H.INT_NUMBER DESC,L.INT_NUMBER_ITEM;

SELECT TOP (30) S.name AS schemaName,O.name AS objectName,O.type_desc,M.definition
FROM [aisinbisa_sap_stagging].sys.sql_modules M
JOIN [aisinbisa_sap_stagging].sys.objects O ON O.object_id=M.object_id
JOIN [aisinbisa_sap_stagging].sys.schemas S ON S.schema_id=O.schema_id
WHERE M.definition LIKE '%CHR_PGI_STATUS%' OR M.definition LIKE '%CHR_GR_STATUS%';
