import './load-env';
import mysql from 'mysql2/promise';
import { Client } from 'pg';

/**
 * ─── PINDAH MASTER: MySQL → PostgreSQL ──────────────────────────────────────
 *
 * Dijalankan SEKALI saat pindah database. Yang dipindahkan hanya tabel master
 * (`TM_*`); riwayat transaksi (`TT_*`) sengaja ditinggal — itu keputusan yang
 * sudah diambil, dan cadangan MySQL tetap disimpan sebagai jejaknya.
 *
 * ── Kenapa id dipertahankan ─────────────────────────────────────────────────
 *
 * Seluruh foreign key menunjuk id. Menomori ulang berarti memetakan ulang
 * setiap rujukan di 26 tabel, dan satu pemetaan yang terlewat menghasilkan
 * baris yang menunjuk part orang lain — salah yang tidak kelihatan sampai
 * seseorang membaca laporan dan menemukan nama yang tidak masuk akal.
 *
 * Itu sebabnya kolom id memakai `GENERATED BY DEFAULT AS IDENTITY`, bukan
 * `ALWAYS`: yang kedua menolak insert yang menyebutkan id-nya sendiri.
 *
 * ── Urutannya tidak ditulis tangan ──────────────────────────────────────────
 *
 * Urutan pemindahan diturunkan dari graf foreign key di katalog Postgres, lalu
 * diurutkan secara topologis. Daftar urutan yang ditulis tangan akan basi pada
 * penambahan tabel berikutnya, dan basinya baru ketahuan saat pemindahan gagal
 * di tengah jalan.
 *
 * ── Zona waktu: inilah bagian yang paling mudah salah ───────────────────────
 *
 * Di MySQL, kolom waktu tidak menyimpan zona. Dua pihak menulisinya dengan
 * acuan berbeda:
 *
 *   DTM_CREATED_AT / DTM_UPDATED_AT  diisi MySQL sendiri lewat
 *                                    DEFAULT CURRENT_TIMESTAMP → waktu LOKAL
 *   kolom waktu lainnya              diisi aplikasi Node → UTC
 *
 * Memperlakukan semuanya sebagai UTC akan menggeser kolom buatan MySQL tujuh
 * jam ke depan; memperlakukan semuanya lokal menggeser sisanya tujuh jam ke
 * belakang. Karena itu keduanya dibedakan di sini, sekali, lalu selesai —
 * sesudah pindah, `timestamptz` membuat persoalan ini tidak ada lagi.
 *
 * ── Pemakaian ───────────────────────────────────────────────────────────────
 *
 *   MYSQL_SOURCE_URL=mysql://user:sandi@mysql:3306/avicenna \
 *   DATABASE_URL=postgresql://... \
 *   node dist/pindah-master.js            # uji coba, TIDAK menulis apa pun
 *   node dist/pindah-master.js --tulis    # sungguhan
 */

/** Zona waktu yang dipakai MySQL saat mengisi DEFAULT CURRENT_TIMESTAMP. */
const ZONA_MYSQL = process.env.PINDAH_ZONA_MYSQL ?? '+07:00';

/** Kolom yang diisi MySQL sendiri, bukan oleh aplikasi. */
const KOLOM_WAKTU_LOKAL = new Set(['DTM_CREATED_AT', 'DTM_UPDATED_AT']);

const UKURAN_BATCH = 500;

interface Kolom {
  nama: string;
  tipe: string;
}

interface Tabel {
  skema: string;
  nama: string;
  kolom: Kolom[];
  /** Tabel lain yang harus terisi lebih dulu. */
  bergantung: Set<string>;
}

function kunci(t: { skema: string; nama: string }): string {
  return `${t.skema}.${t.nama}`;
}

/** Daftar tabel master beserta kolom dan ketergantungannya, dibaca dari Postgres. */
async function bacaTabel(pg: Client): Promise<Tabel[]> {
  const { rows: tabel } = await pg.query<{ skema: string; nama: string }>(`
    SELECT n.nspname AS skema, c.relname AS nama
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE c.relkind = 'r'
      AND c.relname LIKE 'TM\\_%'
      AND n.nspname NOT IN ('pg_catalog', 'information_schema')
    ORDER BY n.nspname, c.relname`);

  const hasil: Tabel[] = [];
  for (const t of tabel) {
    const { rows: kolom } = await pg.query<Kolom>(
      `SELECT column_name AS nama, data_type AS tipe
       FROM information_schema.columns
       WHERE table_schema = $1 AND table_name = $2
       ORDER BY ordinal_position`,
      [t.skema, t.nama],
    );
    const { rows: fk } = await pg.query<{ skema: string; nama: string }>(
      `SELECT ns.nspname AS skema, rel.relname AS nama
       FROM pg_constraint con
       JOIN pg_class src ON src.oid = con.conrelid
       JOIN pg_namespace sns ON sns.oid = src.relnamespace
       JOIN pg_class rel ON rel.oid = con.confrelid
       JOIN pg_namespace ns ON ns.oid = rel.relnamespace
       WHERE con.contype = 'f' AND sns.nspname = $1 AND src.relname = $2`,
      [t.skema, t.nama],
    );
    hasil.push({
      ...t,
      kolom,
      // Rujukan ke diri sendiri (mis. menu induk) dibuang: ia tidak menentukan
      // urutan antar tabel, dan membiarkannya membuat urutan mustahil disusun.
      bergantung: new Set(fk.map(kunci).filter((k) => k !== kunci(t))),
    });
  }
  return hasil;
}

/** Mengurutkan tabel supaya yang dirujuk selalu terisi lebih dulu. */
function urutkan(tabel: Tabel[]): Tabel[] {
  const adaKunci = new Set(tabel.map(kunci));
  const sisa = [...tabel];
  const selesai = new Set<string>();
  const urut: Tabel[] = [];

  while (sisa.length > 0) {
    const siap = sisa.filter((t) =>
      [...t.bergantung].every((d) => !adaKunci.has(d) || selesai.has(d)),
    );
    if (siap.length === 0) {
      // Lingkaran ketergantungan. Dilaporkan, bukan diterobos diam-diam:
      // menerobosnya berarti insert gagal di tengah dengan pesan FK yang tidak
      // menyebut tabel mana yang sebenarnya bermasalah.
      throw new Error(
        `ketergantungan melingkar antara: ${sisa.map(kunci).join(', ')}. ` +
          'Pindahkan tabel-tabel itu dengan tangan, atau longgarkan FK-nya dulu.',
      );
    }
    for (const t of siap) {
      urut.push(t);
      selesai.add(kunci(t));
      sisa.splice(sisa.indexOf(t), 1);
    }
  }
  return urut;
}

/**
 * Menyesuaikan satu nilai dari MySQL ke tipe kolom Postgres.
 *
 * Nilai waktu dibaca sebagai TEKS (dateStrings), bukan Date: Date dari driver
 * sudah terlanjur ditafsirkan memakai zona proses, dan tafsiran itulah yang
 * ingin kita kendalikan sendiri di sini.
 */
function sesuaikan(nilai: unknown, kolom: Kolom): unknown {
  if (nilai === null || nilai === undefined) return null;

  switch (kolom.tipe) {
    case 'boolean':
      return nilai === 1 || nilai === true || nilai === '1';

    case 'timestamp with time zone': {
      const teks = String(nilai).trim().replace(' ', 'T');
      const zona = KOLOM_WAKTU_LOKAL.has(kolom.nama) ? ZONA_MYSQL : 'Z';
      return `${teks}${zona}`;
    }

    case 'jsonb':
      // mysql2 mengembalikan objek untuk kolom JSON, tetapi string untuk kolom
      // teks yang kebetulan berisi JSON. Keduanya harus mendarat sebagai jsonb.
      if (typeof nilai === 'string') {
        try {
          return JSON.parse(nilai);
        } catch {
          return nilai;
        }
      }
      return nilai;

    default:
      return nilai;
  }
}

async function main(): Promise<void> {
  const tulis = process.argv.includes('--tulis');
  const sumber = process.env.MYSQL_SOURCE_URL;
  const tujuan = process.env.DATABASE_URL;

  if (!sumber) throw new Error('MYSQL_SOURCE_URL belum diset (database MySQL lama).');
  if (!tujuan || !/^postgres/.test(tujuan)) {
    throw new Error('DATABASE_URL harus menunjuk Postgres tujuan.');
  }

  const my = await mysql.createConnection({
    uri: sumber,
    // Waktu dibaca apa adanya sebagai teks — lihat catatan zona waktu di atas.
    dateStrings: true,
    supportBigNumbers: true,
    bigNumberStrings: false,
  });
  const pg = new Client({ connectionString: tujuan });
  await pg.connect();

  const tabel = urutkan(await bacaTabel(pg));
  console.log(`[pindah] ${tabel.length} tabel master, urutan mengikuti foreign key`);
  console.log(tulis ? '[pindah] MODE TULIS\n' : '[pindah] uji coba — tidak ada yang ditulis\n');

  const ringkas: Array<{ tabel: string; sumber: number; tujuan: number; catatan: string }> = [];

  try {
    if (tulis) await pg.query('BEGIN');

    for (const t of tabel) {
      const nama = kunci(t);

      const [adaDiSumber] = await my.query<mysql.RowDataPacket[]>(
        'SELECT COUNT(*) AS n FROM information_schema.tables WHERE table_schema = DATABASE() AND table_name = ?',
        [t.nama],
      );
      if (Number(adaDiSumber[0]?.n ?? 0) === 0) {
        ringkas.push({ tabel: nama, sumber: 0, tujuan: 0, catatan: 'tidak ada di MySQL' });
        continue;
      }

      const { rows: isi } = await pg.query<{ n: string }>(
        `SELECT count(*) AS n FROM "${t.skema}"."${t.nama}"`,
      );
      const sudahAda = Number(isi[0]?.n ?? 0);
      if (sudahAda > 0) {
        // Tabel tujuan yang sudah berisi TIDAK ditimpa. Seed sudah mengisi
        // sebagian master, dan menimpanya berarti menghapus baris yang
        // mungkin sudah dirujuk transaksi baru.
        ringkas.push({
          tabel: nama,
          sumber: 0,
          tujuan: sudahAda,
          catatan: 'DILEWATI — tujuan sudah berisi',
        });
        continue;
      }

      const kolomSumber = new Set<string>();
      const [kolomMy] = await my.query<mysql.RowDataPacket[]>(
        'SELECT column_name AS c FROM information_schema.columns WHERE table_schema = DATABASE() AND table_name = ?',
        [t.nama],
      );
      for (const k of kolomMy) kolomSumber.add(String(k.c));

      // Hanya kolom yang ADA di kedua sisi. Kolom baru di Postgres dibiarkan
      // memakai nilai bawaannya; kolom yang hilang dari Postgres diabaikan.
      const kolom = t.kolom.filter((k) => kolomSumber.has(k.nama));
      const [baris] = await my.query<mysql.RowDataPacket[]>(
        `SELECT ${kolom.map((k) => `\`${k.nama}\``).join(', ')} FROM \`${t.nama}\``,
      );

      if (baris.length > 0 && tulis) {
        const daftarKolom = kolom.map((k) => `"${k.nama}"`).join(', ');
        for (let i = 0; i < baris.length; i += UKURAN_BATCH) {
          const potongan = baris.slice(i, i + UKURAN_BATCH);
          const params: unknown[] = [];
          const nilai = potongan
            .map((row) => {
              const satu = kolom.map((k) => {
                params.push(sesuaikan(row[k.nama], k));
                return `$${params.length}`;
              });
              return `(${satu.join(', ')})`;
            })
            .join(', ');
          await pg.query(
            `INSERT INTO "${t.skema}"."${t.nama}" (${daftarKolom}) VALUES ${nilai}`,
            params,
          );
        }

        /*
         * Urutan identity dimajukan melewati id tertinggi.
         *
         * Tanpa ini, insert BERIKUTNYA dari aplikasi memakai angka 1 dan
         * langsung bertabrakan dengan baris yang baru saja dipindah. Gejalanya
         * muncul di tangan operator, bukan di sini: simpan master pertama
         * sesudah go-live gagal dengan "duplicate key".
         */
        if (kolom.some((k) => k.nama === 'INT_ID')) {
          await pg.query(
            `SELECT setval(
               pg_get_serial_sequence('"${t.skema}"."${t.nama}"', 'INT_ID'),
               (SELECT COALESCE(MAX("INT_ID"), 1) FROM "${t.skema}"."${t.nama}")
             )`,
          );
        }
      }

      ringkas.push({
        tabel: nama,
        sumber: baris.length,
        tujuan: tulis ? baris.length : 0,
        catatan: baris.length === 0 ? 'kosong di MySQL' : '',
      });
    }

    if (tulis) {
      await pg.query('COMMIT');
      console.log('[pindah] seluruhnya tersimpan dalam satu transaksi.\n');
    }
  } catch (err) {
    if (tulis) await pg.query('ROLLBACK').catch(() => undefined);
    console.error('\n[pindah] GAGAL — tidak ada yang tersimpan. Perbaiki lalu ulangi.\n');
    throw err;
  } finally {
    await my.end();
    await pg.end();
  }

  const lebar = Math.max(...ringkas.map((r) => r.tabel.length));
  for (const r of ringkas) {
    console.log(`  ${r.tabel.padEnd(lebar)}  ${String(r.sumber).padStart(6)} baris  ${r.catatan}`);
  }
  const total = ringkas.reduce((n, r) => n + r.sumber, 0);
  console.log(`\n[pindah] total ${total} baris master.`);
  if (!tulis) console.log('[pindah] jalankan ulang dengan --tulis untuk menyimpannya.');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
